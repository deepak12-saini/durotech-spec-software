			 <h3>How COVID-19 spreads:</h3>
		     <p>When someone who has COVID-19 coughs or exhales they release droplets of infected fluid. Most of these droplets  fall  on  nearby surfaces  and  objects -such  as desks,  tables or  telephones.  People  could  catch COVID-19 by touching contaminated surfaces or objects –and then touching their eyes, nose or mouth. If they are standing within one meterof a person with COVID-19 they can catch it by breathing in droplets coughed out or exhaled by them. In other words, COVID-19 spreads in a similar way to flu. Most persons infected with COVID-19 experience mild symptoms and recover. </p>
			 
