CREATE TABLE IF NOT EXISTS spec_projects (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    architect VARCHAR(255) NULL,
    location VARCHAR(255) NULL,
    application VARCHAR(40) NOT NULL DEFAULT 'wet_areas',
    area_m2 VARCHAR(40) NULL,
    owner VARCHAR(255) NULL,
    follow_up_on DATE NULL,
    stage VARCHAR(40) NOT NULL DEFAULT 'brief_received',
    revision VARCHAR(20) NOT NULL DEFAULT 'A',
    substrate TEXT NULL,
    proposed_system VARCHAR(255) NULL,
    document_url VARCHAR(500) NULL,
    scope_notes TEXT NULL,
    reviewer VARCHAR(255) NULL,
    review_date DATE NULL,
    review_outcome TEXT NULL,
    created_by INT UNSIGNED NULL,
    created DATETIME NULL,
    modified DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_spec_projects_code (code),
    KEY idx_spec_projects_stage (stage, follow_up_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
